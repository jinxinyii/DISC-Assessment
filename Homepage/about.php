        <h1 class="text-3xl font-bold mb-4 text-center text-[#2b57b5]">ABOUT THE DISC ASSESSMENT</h1>
        <h2 class="text-2xl font-semibold mb-2">What is DISC?</h2>
        <p class="mb-4 text-justify">The DISC Assessment is a personality profiling tool designed to analyze behavioral styles. It categorizes individuals into four primary personality types: Dominance (D), Influence (I), Steadiness (S), and Conscientiousness (C). Dominance represents results-driven, confident, and assertive individuals. Influence describes outgoing, persuasive, and enthusiastic personalities. Steadiness reflects those who are patient, loyal, and team-oriented. Conscientiousness characterizes analytical, detail-oriented, and precise individuals. This assessment helps individuals and organizations improve communication, teamwork, and leadership effectiveness.</p>
        
        <h2 class="text-2xl font-semibold mb-2">History and Development</h2>
        <p class="mb-4 text-justify">The DISC model was originally developed by Dr. William Moulton Marston in 1928 in his book Emotions of Normal People. While Marston introduced the theory, the formal assessment was later created in the 1950s by Walter Clarke, an industrial psychologist. Over the years, the DISC assessment has been widely used in businesses, coaching, and personal development.</p>
        
        <h2 class="text-2xl font-semibold mb-2">Purpose of DISC Assessment</h2>
        <p class="mb-4 text-justify">The DISC assessment is designed to enhance self-awareness and behavioral understanding, improve workplace communication and teamwork, assist in leadership development and management training, support recruitment and career growth by identifying personality-job fit, and resolve conflicts by understanding different perspectives.</p>
        
        <h2 class="text-2xl font-semibold mb-2">Why is DISC Important?</h2>
        <p class="mb-4 text-justify">Understanding DISC personalities helps individuals and organizations communicate effectively by adapting to different behavioral styles, improve teamwork by fostering better collaboration and reducing conflicts, boost productivity by placing people in roles suited to their strengths, and develop leadership skills by learning how to manage different personalities.</p>
        
        <h2 class="text-2xl font-semibold mb-2">Applications of DISC</h2>
        <p class="mb-4 text-justify">DISC is widely used in various fields, including business and HR for recruitment, team-building, and leadership training. It plays a key role in sales and customer service by helping professionals adapt their techniques based on customer behavior. In education and coaching, DISC supports personal growth and student engagement strategies. It is also valuable for personal development, allowing individuals to understand their strengths and areas for improvement.</p>
        
